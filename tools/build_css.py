"""Scope each theme's stylesheet to its theme.

Edit the readable sources in assets/css/src/ (light.css, dark.css), then run:

    python tools/build_css.py

Every rule in src/light.css is prefixed with html[data-theme="light"], every rule
in src/dark.css with html[data-theme="dark"], and each file's @keyframes get a
theme suffix so the two themes never collide. Output: assets/css/light.css and
assets/css/dark.css. Shared rules (theme switch, transitions) live in
assets/css/theme.css and are written by hand.
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CSS = ROOT / "assets" / "css"


def split_top(css):
    """Split a stylesheet into (prelude, body) blocks and bare statements."""
    out, i, n = [], 0, len(css)
    while i < n:
        if css.startswith("/*", i):
            j = css.index("*/", i) + 2
            out.append(("comment", css[i:j]))
            i = j
            continue
        if css[i].isspace():
            i += 1
            continue
        j = i
        while j < n and css[j] not in "{;":
            j += 1
        if j >= n:
            break
        if css[j] == ";":
            out.append(("stmt", css[i:j + 1].strip()))
            i = j + 1
            continue
        prelude = css[i:j].strip()
        depth, k = 1, j + 1
        while depth:
            if css.startswith("/*", k):
                k = css.index("*/", k) + 2
                continue
            if css[k] == "{":
                depth += 1
            elif css[k] == "}":
                depth -= 1
            k += 1
        out.append(("block", prelude, css[j + 1:k - 1]))
        i = k
    return out


def split_selectors(sel):
    parts, depth, cur = [], 0, ""
    for ch in sel:
        if ch in "([":
            depth += 1
        elif ch in ")]":
            depth -= 1
        if ch == "," and depth == 0:
            parts.append(cur.strip())
            cur = ""
        else:
            cur += ch
    parts.append(cur.strip())
    return parts


def scope_selector(s, root):
    s = " ".join(s.split())
    if s in (":root", "html"):
        return root
    if s.startswith("html"):
        return root + s[4:]
    if s.startswith(".js"):
        return root + ".js" + s[3:]
    return f"{root} {s}"


def scope(css, root, suffix, names):
    lines = []
    for item in split_top(css):
        kind = item[0]
        if kind == "comment":
            lines.append(item[1])
        elif kind == "stmt":
            lines.append(item[1])
        else:
            prelude, body = item[1], item[2]
            if prelude.startswith("@keyframes"):
                name = prelude.split()[1]
                lines.append(f"@keyframes {name}-{suffix} {{{body}}}")
            elif prelude.startswith(("@media", "@supports")):
                inner = scope(body, root, suffix, names)
                lines.append(prelude + " {\n" + "\n".join("  " + l for l in inner.splitlines()) + "\n}")
            else:
                sels = ",\n".join(scope_selector(s, root) for s in split_selectors(prelude))
                lines.append(f"{sels} {{{body}}}")
    out = "\n".join(lines)
    # point animations at the renamed keyframes
    for name in names:
        out = re.sub(rf"(animation(?:-name)?\s*:[^;{{}}]*?)\b{re.escape(name)}\b", rf"\g<1>{name}-{suffix}", out)
    return out


for theme in ("light", "dark"):
    src = (CSS / "src" / f"{theme}.css").read_text(encoding="utf-8")
    names = re.findall(r"@keyframes\s+([\w-]+)", src)
    root = f'html[data-theme="{theme}"]'
    head = f"/* GENERATED by tools/build_css.py from assets/css/src/{theme}.css. Edit the source, not this file. */\n"
    (CSS / f"{theme}.css").write_text(head + scope(src, root, theme, names) + "\n", encoding="utf-8")
    print(f"{theme}.css written ({len(names)} keyframes renamed: {', '.join(names)})")
